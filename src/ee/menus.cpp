// menus.cpp: main menu without the entries that need Steam.
// Target: Soldiers.exe R1.28.8 (sha256 5291a092). Settings: [EE] HideMultiplayer, HideMods.
//
// The main menu page (class eDP_MainMenu, vtable 0x835dcc) is built by its Create method 0x4fbe70 (vtable slot
// +0x48). For every entry it does: text = lookup("button/<name>") (0x74dea0), button = new eMenuTextbutton(page,
// text) (0x4fe770, appended to the page's child list), button->command(page, 2, id) (0x4f5b20: the button keeps
// its own "send event 2 with <id> to the page" record), then frees the temporary text. Ids: 4 single player,
// 5 multi player, 6 training, 7 options, 8 credits, 9 mods, 0 exit. After all entries, the same function walks the
// child list and stacks every child (except "noalign") from 1/6 of the page height downwards by each child's own
// height; a child named "back" goes to the bottom. Positions are code, not data: main_menu_skin.reg holds only
// colours and fonts. The page's event handler 0x4fc730 switches on the id (5 -> page "mp_start", 9 -> page
// "mod_change"). Nothing else holds the button objects: the multi-player button pointer lives only in a register
// for the Steam check right after it (no Steam -> button greyed: flag 4 of +0x24 cleared, slot +0x18).
//
// Cleanest change: skip the creation block of an entry with one jump. The skipped block is self-contained
// (temporary text built and freed inside it, stack balanced, exception-unwind state 2 at both ends, only ebx =
// page is live across it and it is not touched). The entry then never exists: no object, no command record, no
// event; the stacking loop closes the gap by itself. The handler's case 5 / case 9 stays in the program but
// nothing can send it any more.
//   HideMultiplayer=1: 0x4fc0cd "push 0x836030 (button/multi_player)" -> "jmp 0x4fc1b8" (the "button/training"
//                      block). Gate: all 240 bytes 0x4fc0cd..0x4fc1bc (the whole skipped block + the first
//                      instruction of the training block).
//   HideMods=1:        0x4fc3cd "push 0x836074 (button/mods)" -> "jmp 0x4fc46d" (the "button/exit" block).
//                      Gate: all 165 bytes 0x4fc3cd..0x4fc471.
// Left alone on purpose: the command-line lobby join after the menu is built (0x4fc624, "cmdline/connect_lobby":
// only filled by a Steam invite start, never without Steam; it does not use the button), the in-mission Esc menu
// (a different page, "game_menu").
